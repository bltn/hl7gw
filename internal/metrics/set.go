package metrics

import (
	"net/http"
	"runtime"

	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/collectors"
	"github.com/prometheus/client_golang/prometheus/promhttp"
)

type Set struct {
	messagesTotal          *prometheus.CounterVec
	deliveryAttemptsTotal  *prometheus.CounterVec
	acksTotal              *prometheus.CounterVec
	connectionsTotal       *prometheus.CounterVec
	tlsHandshakeFailures   *prometheus.CounterVec
	persistenceErrorsTotal *prometheus.CounterVec
	messagesInFlight       *prometheus.GaugeVec
	connectionsOpen        *prometheus.GaugeVec
	acceptPaused           *prometheus.GaugeVec
	tlsCertExpiry          *prometheus.GaugeVec
	messageDuration        *prometheus.HistogramVec
	deliveryDuration       *prometheus.HistogramVec
	registry               *prometheus.Registry
}

type Channel struct {
	MessagesTotal          *prometheus.CounterVec
	DeliveryAttemptsTotal  *prometheus.CounterVec
	AcksTotal              *prometheus.CounterVec
	ConnectionsTotal       *prometheus.CounterVec
	PersistenceErrorsTotal *prometheus.CounterVec
	TLSHandshakeFailures   prometheus.Counter
	MessagesInFlight       prometheus.Gauge
	ConnectionsOpen        prometheus.Gauge
	AcceptPaused           prometheus.Gauge
	TLSCertExpiry          prometheus.Gauge
	MessageDuration        prometheus.Observer
	DeliveryDuration       prometheus.Observer
}

func New(version, commit string) *Set {
	s := &Set{
		messagesTotal:          counter("hl7gw_messages_total", "Inbound messages by processing outcome.", "channel", "outcome"),
		deliveryAttemptsTotal:  counter("hl7gw_delivery_attempts_total", "HTTP delivery attempts to the downstream by result and status code.", "channel", "origin", "result", "status_code"),
		acksTotal:              counter("hl7gw_acks_total", "MLLP ACKs generated by acknowledgement code.", "channel", "code"),
		connectionsTotal:       counter("hl7gw_connections_total", "MLLP connections closed by reason.", "channel", "close_reason"),
		tlsHandshakeFailures:   counter("hl7gw_tls_handshake_failures_total", "Failed mTLS handshakes.", "channel"),
		persistenceErrorsTotal: counter("hl7gw_persistence_errors_total", "Failed journal writes by operation.", "channel", "operation"),
		messagesInFlight:       gauge("hl7gw_messages_in_flight", "Messages read but not yet acknowledged.", "channel"),
		connectionsOpen:        gauge("hl7gw_connections_open", "Open MLLP connections.", "channel"),
		acceptPaused:           gauge("hl7gw_accept_paused", "1 while the listener is at its connection limit and not accepting.", "channel"),
		tlsCertExpiry:          gauge("hl7gw_tls_cert_expiry_timestamp_seconds", "NotAfter of the served mTLS server certificate as a unix timestamp.", "channel"),
		messageDuration:        histogram("hl7gw_message_duration_seconds", "Time from frame read to ACK written.", "channel"),
		deliveryDuration:       histogram("hl7gw_delivery_duration_seconds", "Duration of each HTTP delivery attempt.", "channel"),
		registry:               prometheus.NewRegistry(),
	}
	buildInfo := gauge("hl7gw_build_info", "Build metadata; always 1.", "version", "commit", "go_version")
	buildInfo.WithLabelValues(version, commit, runtime.Version()).Set(1)

	s.registry.MustRegister(
		s.messagesTotal, s.deliveryAttemptsTotal, s.acksTotal, s.connectionsTotal,
		s.tlsHandshakeFailures, s.persistenceErrorsTotal, s.messagesInFlight,
		s.connectionsOpen, s.acceptPaused, s.tlsCertExpiry, s.messageDuration,
		s.deliveryDuration, buildInfo,
		collectors.NewGoCollector(),
		collectors.NewProcessCollector(collectors.ProcessCollectorOpts{}),
	)
	return s
}

func (s *Set) Channel(name string) *Channel {
	labels := prometheus.Labels{"channel": name}
	return &Channel{
		MessagesTotal:          s.messagesTotal.MustCurryWith(labels),
		DeliveryAttemptsTotal:  s.deliveryAttemptsTotal.MustCurryWith(labels),
		AcksTotal:              s.acksTotal.MustCurryWith(labels),
		ConnectionsTotal:       s.connectionsTotal.MustCurryWith(labels),
		PersistenceErrorsTotal: s.persistenceErrorsTotal.MustCurryWith(labels),
		TLSHandshakeFailures:   s.tlsHandshakeFailures.WithLabelValues(name),
		MessagesInFlight:       s.messagesInFlight.WithLabelValues(name),
		ConnectionsOpen:        s.connectionsOpen.WithLabelValues(name),
		AcceptPaused:           s.acceptPaused.WithLabelValues(name),
		TLSCertExpiry:          s.tlsCertExpiry.WithLabelValues(name),
		MessageDuration:        s.messageDuration.WithLabelValues(name),
		DeliveryDuration:       s.deliveryDuration.WithLabelValues(name),
	}
}

func (s *Set) Handler() http.Handler {
	return promhttp.HandlerFor(s.registry, promhttp.HandlerOpts{})
}

func counter(name, help string, labels ...string) *prometheus.CounterVec {
	return prometheus.NewCounterVec(prometheus.CounterOpts{Name: name, Help: help}, labels)
}

func gauge(name, help string, labels ...string) *prometheus.GaugeVec {
	return prometheus.NewGaugeVec(prometheus.GaugeOpts{Name: name, Help: help}, labels)
}

func histogram(name, help string, labels ...string) *prometheus.HistogramVec {
	return prometheus.NewHistogramVec(prometheus.HistogramOpts{Name: name, Help: help, Buckets: prometheus.DefBuckets}, labels)
}
